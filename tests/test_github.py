class _PagedRunner:
    def __init__(self, comments):
        self.comments = comments

    def run(self, args, *, cwd, check=True, **_kwargs):
        endpoint = args[-1]
        if endpoint == "user":
            return SimpleNamespace(returncode=0, stdout=json.dumps({"login": ACTOR[0], "id": ACTOR[1]}))
        page = int(endpoint.rsplit("page=", 1)[1])
        return SimpleNamespace(returncode=0, stdout=json.dumps(self.comments if page == 1 else []))


def _rest(comment_id, body):
    return {
        "id": comment_id,
        "body": body,
        "user": {"login": ACTOR[0], "id": ACTOR[1]},
        "created_at": "2026-09-25T00:00:00Z",
        "updated_at": "2026-09-25T00:00:00Z",
    }


def test_authenticated_reread_strips_exactly_one_footer_at_ingestion(tmp_path, logged):
    view = read_authenticated_protocol_comments(
        _PagedRunner([
            _rest(1, "record"),
            _rest(2, "record" + FOOTER),
            _rest(3, "record" + FOOTER + FOOTER),
            _rest(4, "record" + FOOTER + "\n"),
        ]),
        config=make_config(tmp_path),
        surface_kind="pr",
        number=7,
    )

    bodies = {item.comment_id: item.body for item in view.authored}
    assert bodies[1] == "record"
    assert bodies[2] == "record"
    # One strip only: a doubled footer still reaches strict parsers with one
    # footer attached, and whitespace variants are untouched.
    assert bodies[3] == "record" + FOOTER
    assert bodies[4] == "record" + FOOTER + "\n"
    # Footers seen only on re-read are logged, once.
    assert len(logged) == 1 and "re-read" in logged[0]


def test_footer_log_latch_is_per_invocation(tmp_path, logged):
    config = make_config(tmp_path)

    note_host_footer_observed(config, "first")
    note_host_footer_observed(config, "second")
    assert len(logged) == 1
    reset_host_footer_log_latch()
    note_host_footer_observed(config, "third")
    assert len(logged) == 2
