class _EchoRunner:
    """Echo each write the way a host that stores ``stored(posted)`` would."""

    def __init__(self, *, stored, envelope_extra=None, comment_id=41):
        self.stored = stored
        self.envelope_extra = dict(envelope_extra or {})
        self.comment_id = comment_id
        self.calls: list[list[str]] = []

    def run(self, args, *, cwd, check=True, input_text=None, **_kwargs):
        cmd = list(args)
        self.calls.append(cmd)
        # Reconciliation baseline reads (#510): the actor lookup and an empty listing.
        if cmd[1:3] == ["api", "user"]:
            return SimpleNamespace(
                returncode=0, stderr="",
                stdout=json.dumps({"login": ACTOR[0], "id": ACTOR[1]}),
            )
        if "--method" not in cmd and "--input" not in cmd and any(
            isinstance(part, str) and "/comments?per_page=" in part for part in cmd
        ):
            return SimpleNamespace(returncode=0, stdout="[]", stderr="")
        posted = None
        for part in cmd:
            if isinstance(part, str) and part.startswith("body="):
                posted = part[len("body="):]
        if posted is None and input_text is not None:
            posted = json.loads(input_text)["body"]
        envelope = {
            "id": self.comment_id,
            "body": self.stored(posted),
            "user": {"login": ACTOR[0], "id": ACTOR[1]},
            "created_at": "2026-09-25T00:00:00Z",
        }
        envelope.update(self.envelope_extra)
        return SimpleNamespace(returncode=0, stdout=json.dumps(envelope), stderr="")


