FOOTER = KNOWN_HOST_COMMENT_FOOTER
ACTOR = ("agent-loop", 7)
NEAR_MISSES = (
    # A different URL.
    "\n\n---\n_Generated by [Claude Code](http://claude.ai/code)_",
    # A missing blank line.
    "\n---\n_Generated by [Claude Code](https://claude.ai/code)_",
    # Extra trailing text or whitespace.
    FOOTER + "\n",
    FOOTER + " ",
    FOOTER + "\n\nsmuggled",
    # A doubled footer.
    FOOTER + FOOTER,
    # Ordinary prose.
    "\n\nThanks!",
)


def _body(text: str = "Visible label\n\n<!-- AGENT_MANAGED_CI_INTENT_V2 {} -->") -> TrustedBody:
    return TrustedBody.canonical(text, expected_tokens=("AGENT_MANAGED_CI_INTENT_V2",))


