    # footer attached, and whitespace variants are untouched.
    assert bodies[3] == "record" + FOOTER
    assert bodies[4] == "record" + FOOTER + "\n"
    # Footers seen only on re-read are logged, once.
    assert len(logged) == 1 and "re-read" in logged[0]


