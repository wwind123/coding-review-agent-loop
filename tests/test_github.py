class _EchoRunner:
    """Echo each write the way a host that stores ``stored(posted)`` would."""

    def __init__(self, *, stored, envelope_extra=None, comment_id=41):
        self.stored = stored
        self.envelope_extra = dict(envelope_extra or {})
        self.comment_id = comment_id
        self.calls: list[list[str]] = []

    def run(self, args, *, cwd, check=True, input_text=None, **_kwargs):
        cmd = list(args)
        self.calls.append(cmd)
        posted = None
        for part in cmd:
            if isinstance(part, str) and part.startswith("body="):
                posted = part[len("body="):]
        if posted is None and input_text is not None:
            posted = json.loads(input_text)["body"]
        envelope = {
            "id": self.comment_id,
            "body": self.stored(posted),
            "user": {"login": ACTOR[0], "id": ACTOR[1]},
            "created_at": "2026-09-25T00:00:00Z",
        }
        envelope.update(self.envelope_extra)
        return SimpleNamespace(returncode=0, stdout=json.dumps(envelope), stderr="")


def _post_pr(tmp_path, runner, body=None):
    return post_verified_trusted_pr_protocol_comment_observed(
        runner,
        config=make_config(tmp_path),
        pr_number=7,
        body=body or _body(),
        expected_author_login=ACTOR[0],
        expected_author_id=ACTOR[1],
    )


def test_footer_constant_is_the_observed_suffix_and_carries_no_marker():
    assert FOOTER == "\n\n---\n_Generated by [Claude Code](https://claude.ai/code)_"
    assert not FOOTER.endswith("\n")
    assert scan_reserved_markers(FOOTER) == ()
    assert "<!--" not in FOOTER


def test_strip_removes_exactly_one_trailing_footer_and_nothing_else():
    assert strip_known_host_footer("record" + FOOTER) == ("record", True)
    assert strip_known_host_footer("record") == ("record", False)
    # Never loops: a doubled footer keeps one footer attached.
    assert strip_known_host_footer("record" + FOOTER + FOOTER) == ("record" + FOOTER, True)
    # Never trims whitespace or touches earlier text.
    assert strip_known_host_footer("record" + FOOTER + "\n") == ("record" + FOOTER + "\n", False)
    assert strip_known_host_footer(FOOTER + "record") == (FOOTER + "record", False)


def test_stored_body_match_accepts_only_posted_or_posted_plus_one_footer():
    assert stored_body_matches_posted("posted", "posted") == (True, False)
    assert stored_body_matches_posted("posted" + FOOTER, "posted") == (True, True)
    for suffix in NEAR_MISSES:
        assert stored_body_matches_posted("posted" + suffix, "posted") == (False, False)
    assert stored_body_matches_posted(FOOTER + "posted", "posted") == (False, False)
    assert stored_body_matches_posted(None, "posted") == (False, False)


def test_readback_accepts_exact_footer_on_create_and_logs_once(tmp_path, logged):
    runner = _EchoRunner(
        stored=lambda posted: posted + FOOTER,
        envelope_extra={"updated_at": "2026-09-25T00:00:05Z"},
    )

    written = _post_pr(tmp_path, runner)
    again = _post_pr(tmp_path, runner)

    assert written.comment_id == 41 and again.comment_id == 41
    assert written.host_footer_observed is True
    assert written.server_updated_at == 1790294405
    assert len(logged) == 1 and "known comment footer" in logged[0]
    # The int-returning wrapper keeps its contract.
    assert post_verified_trusted_pr_protocol_comment(
        runner, config=make_config(tmp_path), pr_number=7, body=_body(),
        expected_author_login=ACTOR[0], expected_author_id=ACTOR[1],
    ) == 41


def test_readback_accepts_exact_footer_on_patch(tmp_path, logged):
    runner = _EchoRunner(stored=lambda posted: posted + FOOTER)

    written = patch_verified_trusted_protocol_comment_observed(
        runner, config=make_config(tmp_path), comment_id=41, body=_body(),
        expected_author_login=ACTOR[0], expected_author_id=ACTOR[1],
    )

    assert (written.comment_id, written.host_footer_observed) == (41, True)
    assert patch_verified_trusted_protocol_comment(
        runner, config=make_config(tmp_path), comment_id=41, body=_body(),
        expected_author_login=ACTOR[0], expected_author_id=ACTOR[1],
    ) == 41
    assert len(logged) == 1


@pytest.mark.parametrize(
    ("envelope_extra", "expected"),
    [
        ({"updated_at": "2026-09-25T00:10:00Z"}, 1790294400 + 600),
        ({}, None),
        # created_at is the comment's immutable creation time and is never a
        # stand-in for a PATCH's server time.
        ({"created_at": "2026-09-24T23:40:00Z"}, None),
        ({"updated_at": "not a time"}, None),
        ({"updated_at": 12}, None),
    ],
)
def test_server_updated_at_comes_only_from_updated_at(tmp_path, logged, envelope_extra, expected):
    runner = _EchoRunner(stored=lambda posted: posted, envelope_extra=envelope_extra)

    written = patch_verified_trusted_protocol_comment_observed(
        runner, config=make_config(tmp_path), comment_id=41, body=_body(),
        expected_author_login=ACTOR[0], expected_author_id=ACTOR[1],
    )

    assert written.server_updated_at == expected


@pytest.mark.parametrize("suffix", NEAR_MISSES)
def test_readback_rejects_near_miss_and_doubled_footers(tmp_path, logged, suffix):
    runner = _EchoRunner(stored=lambda posted: posted + suffix)

    with pytest.raises(AgentLoopError, match="returned a different body"):
        _post_pr(tmp_path, runner)
    with pytest.raises(AgentLoopError, match="returned a different body"):
        patch_verified_trusted_protocol_comment_observed(
            runner, config=make_config(tmp_path), comment_id=41, body=_body(),
            expected_author_login=ACTOR[0], expected_author_id=ACTOR[1],
        )
    assert logged == []


