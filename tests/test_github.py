def test_footer_constant_is_the_observed_suffix_and_carries_no_marker():
    assert FOOTER == "\n\n---\n_Generated by [Claude Code](https://claude.ai/code)_"
    assert not FOOTER.endswith("\n")
    assert scan_reserved_markers(FOOTER) == ()
    assert "<!--" not in FOOTER


def test_strip_removes_exactly_one_trailing_footer_and_nothing_else():
    assert strip_known_host_footer("record" + FOOTER) == ("record", True)
    assert strip_known_host_footer("record") == ("record", False)
    # Never loops: a doubled footer keeps one footer attached.
    assert strip_known_host_footer("record" + FOOTER + FOOTER) == ("record" + FOOTER, True)
    # Never trims whitespace or touches earlier text.
    assert strip_known_host_footer("record" + FOOTER + "\n") == ("record" + FOOTER + "\n", False)
    assert strip_known_host_footer(FOOTER + "record") == (FOOTER + "record", False)


def test_stored_body_match_accepts_only_posted_or_posted_plus_one_footer():
    assert stored_body_matches_posted("posted", "posted") == (True, False)
    assert stored_body_matches_posted("posted" + FOOTER, "posted") == (True, True)
    for suffix in NEAR_MISSES:
        assert stored_body_matches_posted("posted" + suffix, "posted") == (False, False)
    assert stored_body_matches_posted(FOOTER + "posted", "posted") == (False, False)
    assert stored_body_matches_posted(None, "posted") == (False, False)


