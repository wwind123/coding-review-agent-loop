class _PagedRunner:
    def __init__(self, comments):
        self.comments = comments

    def run(self, args, *, cwd, check=True, **_kwargs):
        endpoint = args[-1]
        if endpoint == "user":
            return SimpleNamespace(returncode=0, stdout=json.dumps({"login": ACTOR[0], "id": ACTOR[1]}))
        page = int(endpoint.rsplit("page=", 1)[1])
        return SimpleNamespace(returncode=0, stdout=json.dumps(self.comments if page == 1 else []))


